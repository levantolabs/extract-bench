import copy
import hashlib
import json
import random
import re
import subprocess
import sys
import tempfile
import time

from collections import Counter, OrderedDict
from pathlib import Path

DS = Path(__file__).resolve().parent
sys.path.insert(0, str(DS / "scripts"))
import realdoc_official as R  # noqa: E402  (our vendored verbatim copy; not from raw/)

KEY = "realdoc"
SEED = 20
N = 200
HOLDOUT_FRAC = 0.20
MAX_PAGES = 4
MAX_IMG = 4 * 1024 * 1024
MAX_TOTAL = 8 * 1024 * 1024
DPI = 150
HF_REPO = "Extend-AI/RealDoc-Bench"
HF_REV = "08dde9d20d844943fc328b161f9d332c7e8bdee4"
GH_SHA = "fb26a6876481de76dc293f722ab4efa71279904d"
SHA_BANK = "70f21b748a584001a9ad42cfe88a5c465cf9e332e600ef5e63b212a9ffffcce6"
SHA_MANIFEST = "ad47e62a8458d7b6ba64e9c2960c96fc0007fadf3b0c713c89c4a257a2be5745"
UPSTREAM_EVAL = DS / "raw" / "github" / "src" / f"realdoc-bench-{GH_SHA}" / "realdoc_bench" / "evaluate"
PDFINFO, PDFTOPPM, PDFTOTEXT = "/opt/homebrew/bin/pdfinfo", "/opt/homebrew/bin/pdftoppm", "/opt/homebrew/bin/pdftotext"

POPPLER = "UNKNOWN"
RAW = DS / "raw"
DOCS = RAW / "docs"
IMG = DS / "img"
TXT = DS / "textlayer"

USE_CASE = {
    "finance": "Finance / insurance forms (scanned forms, field-value pairing)",
    "medical_healthcare": "Medical / healthcare forms (scanned forms, field-value pairing)",
    "mortgage": "Mortgage / real-estate forms (scanned forms, field-value pairing)",
    "supply_chain": "Supply-chain documents: invoices, orders, shipping forms (field-value pairing)",
}
STATE_WORDS = {"checked", "unchecked", "selected", "unselected", "crossed_out", "filled", "unfilled"}
NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,63}$")
LINE_RE = re.compile(r'^\s*(".*"):\s*<(.+)>,?\s*$')


def poppler_version() -> str:
    out = subprocess.run([PDFTOPPM, "-v"], capture_output=True, text=True, timeout=20)
    m = re.search(r"version\s+([\d.]+)", out.stdout + out.stderr)
    return m.group(1) if m else "UNKNOWN"


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def run(cmd: list[str], timeout: int = 300) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)


# ---------------------------------------------------------------- field plan
def template_hints(template: str) -> "OrderedDict[str, str]":
    """Exact keys -> hint from the official rendered template (keys are json.dumps'd, so json.loads them)."""
    out = OrderedDict()
    for line in template.splitlines():
        m = LINE_RE.match(line)
        if m:
            out[json.loads(m.group(1))] = m.group(2)
    return out


def sanitize(key: str, used: set[str]) -> str:
    s = re.sub(r"[^A-Za-z0-9_]+", "_", key).strip("_")
    s = re.sub(r"_+", "_", s)
    if not s or not re.match(r"[A-Za-z_]", s[0]):
        s = "f_" + s
    if len(s) > 64:
        s = s[:55].rstrip("_") + "_" + hashlib.sha1(key.encode()).hexdigest()[:8]
    base, i = s, 2
    while s in used:
        suf = f"_{i}"
        s = base[: 64 - len(suf)] + suf
        i += 1
    assert NAME_RE.match(s), (key, s)
    used.add(s)
    return s


def enum_options(hint: str) -> list[str]:
    base = hint.replace(" | null", "").strip()
    return [o.strip() for o in base[len("one of:"):].split("|") if o.strip()]


def instructions(question: str, key: str, kind: str, opts: list[str]) -> str:
    """Per-field instructions = the RealDoc question + the answer key + the upstream SYSTEM_PROMPT rule for that
    type hint, paraphrased into one line (rules 1, 3, 4, 5, 6, 6a). Identical for every arm."""
    clause = {
        "text": "Copy the value verbatim as printed on the page (trimmed).",
        "enum": "Answer with exactly one of: " + " | ".join(opts) + ".",
        "number": "Return it as a number (no commas, currency symbols or %).",
        "date": "Return the date as YYYY-MM-DD.",
    }[kind]
    return (f"{question.strip()}\nAnswer field: \"{key}\". {clause} If the value is absent, blank, redacted or "
            f"illegible, return null.")


def field_plan(it: dict) -> dict:
    gold = copy.deepcopy(it["gold_dict"])
    template = R.build_template(it.get("response_format", ""), gold)  # may widen gold in place (upstream rule)
    hints = template_hints(template)
    if set(hints) != set(gold):
        raise ValueError(f"{it['question_id']}: template keys != gold keys")
    str_keys = R.string_keys(template)  # upstream fuzzy-eligible keys (regex on the rendered template)
    used: set[str] = set()
    fields, excluded, notes = [], {}, []
    for k, hint in hints.items():
        g = gold[k]
        base = hint.replace(" | null", "").strip()
        if base == "boolean" or isinstance(g, bool):
            excluded[k] = {"reason": "boolean (no boolean type in Clairic/Sage 2; decision side test)",
                           "realdoc_hint": hint, "gold": g}
            continue
        if base.startswith("list") or isinstance(g, list):
            excluded[k] = {"reason": "list (Sage 2 has no list type; 7 in the whole bank)", "realdoc_hint": hint,
                           "gold": g}
            continue
        f = {"name": sanitize(k, used)}
        opts: list[str] = []
        if base.startswith("one of:"):
            opts = enum_options(hint)
            kind, ftype = "enum", "text"
        elif base == "string":
            kind, ftype = "text", "text"
        elif base in ("integer", "number"):
            kind, ftype = "number", "number"
        elif base.startswith("date"):
            kind, ftype = "date", "date"
        else:
            raise ValueError(f"{it['question_id']}: unknown hint {hint!r}")
        f["type"] = ftype
        f["instructions"] = instructions(it["question"], k, kind, opts)
        f["gold"] = g
        f["realdoc_key"] = k
        f["realdoc_hint"] = hint
        f["fuzzy"] = k in str_keys
        if kind == "enum":
            f["enum_options"] = opts
            f["enum_state"] = all(o.lower() in STATE_WORDS for o in opts)
        if base == "integer":
            if isinstance(g, float) and not g.is_integer():
                notes.append(f"{k}: hint integer but gold {g} is non-integral -> number without integer flag")
            else:
                f["integer"] = True
        fields.append(f)
    return {"template": template, "gold_official": gold, "str_keys": sorted(str_keys), "fields": fields,
            "excluded": excluded, "notes": notes}


# ---------------------------------------------------------------- docs
def fetch_pdf(stem: str) -> Path:
    dst = DOCS / f"{stem}.pdf"
    url = f"https://huggingface.co/datasets/{HF_REPO}/resolve/{HF_REV}/docs/{stem}.pdf"
    tmp = dst.with_suffix(".part")
    for attempt in range(4):
        # curl with a hard per-attempt deadline (urllib once hung >10 min on a trickling CDN connection)
        r = run(["/usr/bin/curl", "-sSfL", "--max-time", "240", "-A", "extract-bench/0.1", "-o", str(tmp), url],
                timeout=300)
        if r.returncode == 0 and tmp.exists() and tmp.read_bytes()[:5] == b"%PDF-":
            tmp.replace(dst)
            return dst
        tmp.unlink(missing_ok=True)
        if attempt == 3:
            raise RuntimeError(f"fetch {stem}: curl rc={r.returncode} {r.stderr[:200]}")
        time.sleep(2 + 3 * attempt)
    return dst


def page_count(pdf: Path) -> int | None:
    out = run([PDFINFO, str(pdf)], timeout=60)
    m = re.search(r"^Pages:\s+(\d+)", out.stdout, re.M)
    return int(m.group(1)) if m else None


def render(stem: str, pdf: Path, pages: int) -> list[dict]:
    """PNG at 150 dpi; JPEG q90 fallback if any page > 4 MiB or total > 8 MiB. Returns per-page records."""
    recs = []
    for fmt in ("png", "jpeg"):
        recs = []
        for p in range(1, pages + 1):
            ext = "png" if fmt == "png" else "jpg"
            dst = IMG / f"{stem}_p{p}.{ext}"
            with tempfile.TemporaryDirectory(prefix="rdb-") as td:
                args = [PDFTOPPM, "-r", str(DPI), "-f", str(p), "-l", str(p), "-singlefile"]
                args += ["-png"] if fmt == "png" else ["-jpeg", "-jpegopt", "quality=90"]
                r = run(args + [str(pdf), str(Path(td) / "o")])
                if r.returncode != 0:
                    raise RuntimeError(f"pdftoppm {stem} p{p}: {r.stderr[:200]}")
                src = Path(td) / f"o.{ext}"
                dst.write_bytes(src.read_bytes())
            recs.append({"path": f"img/{dst.name}", "bytes": dst.stat().st_size, "format": fmt})
        if all(x["bytes"] <= MAX_IMG for x in recs) and sum(x["bytes"] for x in recs) <= MAX_TOTAL:
            if fmt == "jpeg":  # drop stale PNGs of this doc
                for p in range(1, pages + 1):
                    (IMG / f"{stem}_p{p}.png").unlink(missing_ok=True)
            return recs
    raise RuntimeError(f"{stem}: cannot fit pages under 4 MiB each / 8 MiB total at {DPI} dpi")


def png_or_jpeg_size(path: Path) -> list[int]:
    b = path.read_bytes()[:64 * 1024]
    if b[:8] == b"\x89PNG\r\n\x1a\n":
        return [int.from_bytes(b[16:20], "big"), int.from_bytes(b[20:24], "big")]
    i = 2
    while i < len(b) - 9:  # JPEG: scan for SOFn
        if b[i] != 0xFF:
            i += 1
            continue
        mk = b[i + 1]
        if mk in (0xC0, 0xC1, 0xC2):
            return [int.from_bytes(b[i + 7:i + 9], "big"), int.from_bytes(b[i + 5:i + 7], "big")]
        i += 2 + int.from_bytes(b[i + 2:i + 4], "big")
    return [0, 0]


def text_layer(stem: str, pdf: Path) -> dict:
    out = run([PDFTOTEXT, "-layout", "-enc", "UTF-8", str(pdf), "-"], timeout=120)
    t = out.stdout if out.returncode == 0 else ""
    n_alnum = sum(c.isalnum() for c in t)
    rec = {"alnum_chars": n_alnum, "has_text_layer": n_alnum >= 20}
    if rec["has_text_layer"]:
        TXT.mkdir(exist_ok=True)
        (TXT / f"{stem}.txt").write_text(t)
        rec["path"] = f"textlayer/{stem}.txt"
    return rec


def norm_reach(s: str) -> str:
    return re.sub(r"[^0-9a-z]+", "", s.lower())


def reachable(gold, text: str) -> bool | None:
    """Is the gold findable in the text (alnum-squashed, lower-cased)? None for null gold / enums."""
    if gold is None:
        return None
    t = norm_reach(text)
    if isinstance(gold, (int, float)):
        cands = {str(gold)}
        if isinstance(gold, float):
            cands |= {f"{gold:,.2f}", f"{gold:.2f}", f"{gold:,}", (f"{gold:.2f}").rstrip("0").rstrip(".")}
        else:
            cands |= {f"{gold:,}", f"{gold:,.2f}"}
        return any(norm_reach(c) and norm_reach(c) in t for c in cands)
    m = re.fullmatch(r"(\d{4})-(\d{2})-(\d{2})", str(gold))
    if m:  # ISO gold: also try the usual printed US forms (crude; no month names beyond en)
        y, mo, d = (int(x) for x in m.groups())
        months = ["january", "february", "march", "april", "may", "june", "july", "august", "september",
                  "october", "november", "december"]
        cands = {f"{mo:02d}/{d:02d}/{y}", f"{mo}/{d}/{y}", f"{mo:02d}/{d:02d}/{y % 100:02d}", f"{mo}/{d}/{y % 100:02d}",
                 f"{months[mo - 1]} {d}, {y}", f"{months[mo - 1][:3]} {d}, {y}", f"{d} {months[mo - 1]} {y}",
                 str(gold)}
        return any(norm_reach(c) in t for c in cands)
    g = norm_reach(str(gold))
    return bool(g) and g in t


# ---------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fetch", action="store_true", help="download missing PDFs from the pinned HF revision")
    a = ap.parse_args()
    t0 = time.time()
    global POPPLER
    POPPLER = poppler_version()

    bank_p, man_p = RAW / "hf" / "qa_bank.json", RAW / "hf" / "manifest.json"
    assert sha256(bank_p) == SHA_BANK, "qa_bank.json sha256 changed"
    assert sha256(man_p) == SHA_MANIFEST, "manifest.json sha256 changed"
    n_verbatim = R.verify(UPSTREAM_EVAL)
    bank = json.loads(bank_p.read_text())["items"]
    manifest = {d["document_id"]: d for d in json.loads(man_p.read_text())["documents"]}

    plans, eligible = {}, {}
    totals = Counter()
    for it in bank:
        pl = field_plan(it)
        plans[it["question_id"]] = pl
        totals["fields_all"] += len(it["gold_dict"])
        totals["fields_kept"] += len(pl["fields"])
        totals["excluded_boolean"] += sum(1 for v in pl["excluded"].values() if v["reason"].startswith("boolean"))
        totals["excluded_list"] += sum(1 for v in pl["excluded"].values() if v["reason"].startswith("list"))
        if pl["fields"]:
            eligible.setdefault(it["domain"], []).append(it)
    totals["questions_all"] = len(bank)
    totals["questions_eligible"] = sum(len(v) for v in eligible.values())

    # proportional allocation, largest remainder (ties -> domain name)
    tot = totals["questions_eligible"]
    raw_q = {d: N * len(v) / tot for d, v in eligible.items()}
    quota = {d: int(x) for d, x in raw_q.items()}
    for d in sorted(raw_q, key=lambda d: (-(raw_q[d] - quota[d]), d))[: N - sum(quota.values())]:
        quota[d] += 1

    def qkey(it):
        m = re.search(r"_(\d+)$", it["source_file"]), re.search(r"_q(\d+)$", it["question_id"])
        return (int(m[0].group(1)) if m[0] else 0, int(m[1].group(1)) if m[1] else 0, it["question_id"])

    rng = random.Random(SEED)
    DOCS.mkdir(parents=True, exist_ok=True)
    IMG.mkdir(exist_ok=True)
    chosen, dropped, doc_info = [], [], {}
    for d in sorted(eligible):
        order = sorted(eligible[d], key=qkey)
        rng.shuffle(order)
        taken = 0
        for it in order:
            if taken >= quota[d]:
                break
            stem = it["source_file"]
            if stem not in doc_info:
                pdf = DOCS / f"{stem}.pdf"
                if not pdf.exists():
                    if not a.fetch:
                        raise SystemExit(f"missing {pdf}; re-run with --fetch")
                    fetch_pdf(stem)
                man = manifest.get(stem)
                info = {"sha256": sha256(pdf), "pages": page_count(pdf), "bytes": pdf.stat().st_size}
                info["sha_ok"] = bool(man) and man.get("sha256") == info["sha256"]
                doc_info[stem] = info
            info = doc_info[stem]
            if not info["sha_ok"]:
                dropped.append({"question_id": it["question_id"], "doc": stem, "reason": "sha256 != manifest"})
                continue
            if info["pages"] is None or info["pages"] > MAX_PAGES:
                dropped.append({"question_id": it["question_id"], "doc": stem,
                                "reason": f"pages={info['pages']} > {MAX_PAGES}"})
                continue
            chosen.append(it)
            taken += 1
        if taken < quota[d]:
            raise SystemExit(f"{d}: only {taken} of {quota[d]}")

    # render + text layer per unique doc
    for stem in sorted({it["source_file"] for it in chosen}):
        info = doc_info[stem]
        if "images" not in info:
            info["images"] = render(stem, DOCS / f"{stem}.pdf", info["pages"])
            for im in info["images"]:
                im["px"] = png_or_jpeg_size(DS / im["path"])
            info["text_layer"] = text_layer(stem, DOCS / f"{stem}.pdf")

    ids = [f"{KEY}-{it['question_id']}" for it in chosen]
    holdout = set(random.Random(SEED).sample(sorted(ids), round(HOLDOUT_FRAC * len(ids))))

    out_lines, report_fields = [], Counter()
    for iid, it in zip(ids, chosen):
        pl, stem = plans[it["question_id"]], it["source_file"]
        info, man = doc_info[stem], manifest[stem]
        tl = info["text_layer"]
        tl_text = (DS / tl["path"]).read_text() if tl.get("path") else ""
        reach = {f["name"]: (reachable(f["gold"], tl_text) if tl.get("has_text_layer") and "enum_options" not in f
                             else None) for f in pl["fields"]}
        for f in pl["fields"]:
            report_fields["kept_" + ("null" if f["gold"] is None else f["type"])] += 1
            if f.get("enum_options"):
                report_fields["enum_state" if f["enum_state"] else "enum_label"] += 1
        report_fields["excluded"] += len(pl["excluded"])
        meta = {
            "split": "test (HF config 'default', only split)",
            "question_id": it["question_id"],
            "source_file": stem,
            "doc_id": stem,
            "domain": it["domain"],
            "capabilities": it.get("capabilities", []),
            "question": it["question"],
            "response_format": it.get("response_format"),
            "official_template": pl["template"],
            "official_gold_dict": pl["gold_official"],
            "official_str_keys": pl["str_keys"],
            "official_scorer": "realdoc deep_equal / fuzzy_equal for official_str_keys (scripts/realdoc_official.py,"
                               " verbatim from extend-hq/realdoc-bench@" + GH_SHA[:8] + ")",
            "name_map": {f["name"]: f["realdoc_key"] for f in pl["fields"]},
            "excluded_fields": pl["excluded"],
            "n_gold_fields_total": len(pl["gold_official"]),
            "n_fields_scored": len(pl["fields"]),
            "field_notes": pl["notes"],
            "page_count": info["pages"],
            "pdf": f"raw/docs/{stem}.pdf",
            "pdf_sha256": info["sha256"],
            "pdf_bytes": info["bytes"],
            "images_rendered": {"tool": f"poppler pdftoppm {POPPLER}", "dpi": DPI,
                                "pages": [{"path": x["path"], "bytes": x["bytes"], "format": x["format"],
                                           "px": x["px"]} for x in info["images"]]},
            "text_layer": {"has_text_layer": tl["has_text_layer"], "alnum_chars": tl["alnum_chars"],
                           "tool": f"poppler pdftotext {POPPLER} -layout"},
            "alt_texts": ({"pdf_text_layer": tl["path"]} if tl.get("path") else {}),
            "gold_reachable": {"pdf_text_layer": reach} if tl.get("has_text_layer") else {},
            "provenance": {"ai_status": man.get("ai_status"), "source_type": (man.get("source") or {}).get("type"),
                           "source_rights_status": (man.get("source_rights") or {}).get("status"),
                           "document_license": man.get("document_license")},
            "holdout": iid in holdout,
            "hf_revision": HF_REV,
            "scorer_commit": GH_SHA,
        }
        item = {
            "id": iid, "dataset": KEY, "use_case": USE_CASE[it["domain"]], "modality": "image",
            "text": None, "text_source": "none",
            "images": [x["path"] for x in info["images"]],
            "fields": pl["fields"], "metric": "exact_norm", "meta": meta,
        }
        out_lines.append(json.dumps(item, ensure_ascii=False))

    (DS / "items.jsonl").write_text("\n".join(out_lines) + "\n")
    used_imgs = {x["path"] for s in {it["source_file"] for it in chosen} for x in doc_info[s]["images"]}
    stale = [p for p in IMG.iterdir() if f"img/{p.name}" not in used_imgs]
    for p in stale:
        p.unlink()

    report = {
        "built": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "seconds": round(time.time() - t0, 1),
        "hf_revision": HF_REV, "scorer_commit": GH_SHA, "vendored_defs_verified": n_verbatim,
        "bank_totals": dict(totals),
        "eligible_by_domain": {d: len(v) for d, v in sorted(eligible.items())},
        "quota_by_domain": dict(sorted(quota.items())),
        "chosen_by_domain": dict(Counter(it["domain"] for it in chosen)),
        "dropped": dropped, "n_dropped": len(dropped),
        "docs_inspected": len(doc_info),
        "docs_inspected_page_counts": dict(Counter(v["pages"] for v in doc_info.values())),
        "docs_used": len({it["source_file"] for it in chosen}),
        "sample_fields": dict(report_fields),
        "holdout_n": len(holdout),
        "stale_images_removed": len(stale),
        "items_sha256": sha256(DS / "items.jsonl"),
    }
    (DS / "build_report.json").write_text(json.dumps(report, indent=1))
    print(json.dumps({k: v for k, v in report.items() if k != "dropped"}, indent=1))


if __name__ == "__main__":
    main()
