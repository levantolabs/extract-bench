"""Build datasets/realdoc/items.jsonl: RealDoc-Bench QA (Extend), 200 questions stratified by domain, seed 20.

$0 build. No metered API is called. The only network use is `--fetch`, which downloads source PDFs from the
pinned Hugging Face revision (free). Downloaded files are data: nothing in raw/ is imported or executed.
Template building and scoring use VERBATIM copies of the upstream code (scripts/realdoc_official.py,
regenerated by scripts/vendor_official.py and checked against raw/github/... by verify()).

Pipeline
1. Check sha256 of raw/hf/qa_bank.json + manifest.json (HF revision 08dde9d2...).
2. Per question: official typed template = build_template(response_format, gold_dict) (upstream rule, incl.
   widen_types_from_gold). Field plan by template hint (the hint, not the gold's Python type, is the source of
   truth, as in upstream SYSTEM_PROMPT):
     string -> text | one of: ... -> text (options in instructions; enum_state flag if options are
     checkbox-state words) | integer -> number + integer (widened to non-integer number when the gold is a
     non-integral float, a known upstream template bug: '<digits>' with gold 67.15) | number -> number |
     date string YYYY-MM-DD -> date | boolean -> EXCLUDED (meta, decision side test) |
     list of strings -> EXCLUDED. Null gold kept (abstention).
3. Eligible = questions with >= 1 non-excluded field. Allocation over domains proportional to eligible counts
   (largest remainder) for N=200.
4. Order: rng = random.Random(20); for domain in sorted(domains): ids sorted by (doc number, q number) then
   rng.shuffle. Walk each domain's order; accept a question if its PDF exists (or is fetched), its sha256
   matches manifest.json and pdfinfo reports <= 4 pages; otherwise drop and count. Stop at the quota.
5. Render pages with poppler pdftoppm at 150 dpi (upstream _vision_base.DEFAULT_DPI = 150) as PNG; fall back to
   JPEG q90 when a page > 4 MiB or the item's pages total > 8 MiB. Text layer via `pdftotext -layout` kept as
   an alt text when it has >= 20 alphanumeric characters.
6. Sealed 20% holdout: random.Random(20).sample(sorted(ids), 40) -> meta.holdout (SURVEY L13).

Usage (from extract-bench/):
  /opt/homebrew/bin/uv run --no-project python -I datasets/realdoc/build.py [--fetch]
"""
